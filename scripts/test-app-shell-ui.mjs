/** Source guards for the global shell, task center, and long-operation ownership. */
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve} from 'node:path';

test('app shell exposes a global task center and operation bar without the update route', async () => {
  const app = await readFile(resolve(process.cwd(), 'src/App.vue'), 'utf8');
  const router = await readFile(resolve(process.cwd(), 'src/router.ts'), 'utf8');
  const taskDrawer = await readFile(resolve(process.cwd(), 'src/components/TaskDrawer.vue'), 'utf8');
  const overview = await readFile(resolve(process.cwd(), 'src/pages/InstanceOverviewPage.vue'), 'utf8');
  const world = await readFile(resolve(process.cwd(), 'src/pages/WorldPage.vue'), 'utf8');
  const mods = await readFile(resolve(process.cwd(), 'src/pages/ModsPage.vue'), 'utf8');
  const hostMods = await readFile(resolve(process.cwd(), 'src/pages/HostModsPage.vue'), 'utf8');
  const creation = await readFile(resolve(process.cwd(), 'src/composables/useInstanceCreation.ts'), 'utf8');
  const backups = await readFile(resolve(process.cwd(), 'src/pages/BackupsPage.vue'), 'utf8');
  const hostEnvironment = await readFile(resolve(process.cwd(), 'src/composables/useHostEnvironment.ts'), 'utf8');
  const dockerTasks = await readFile(resolve(process.cwd(), 'src/composables/useDockerTasks.ts'), 'utf8');
  const taskRefresh = await readFile(resolve(process.cwd(), 'src/lib/taskRefresh.ts'), 'utf8');
  const releases = await readFile(resolve(process.cwd(), 'src/pages/ReleaseManagementPage.vue'), 'utf8');
  const buildTasks = await readFile(resolve(process.cwd(), 'src/composables/useBuildTasks.ts'), 'utf8');
  const taskStoreSource = await readFile(resolve(process.cwd(), 'src/composables/useTasks.ts'), 'utf8');
  const operationsSource = await readFile(resolve(process.cwd(), 'src/composables/useOperations.ts'), 'utf8');
  const releaseList = await readFile(resolve(process.cwd(), 'src/composables/useReleaseList.ts'), 'utf8');
  const instanceList = await readFile(resolve(process.cwd(), 'src/composables/useInstanceList.ts'), 'utf8');
  const instanceOverview = await readFile(resolve(process.cwd(), 'src/composables/useInstanceOverview.ts'), 'utf8');
  const hostModsPage = await readFile(resolve(process.cwd(), 'src/pages/HostModsPage.vue'), 'utf8');

  assert.match(app, /class="operation-bar"/);
  assert.match(app, /refreshActiveTasks/);
  assert.match(app, /任务记录/);
  assert.doesNotMatch(app, /<span v-if="activityCount" class="nav-count">/);
  assert.doesNotMatch(router, /path: "\/tasks"/);
  assert.match(app, /<TaskDrawer\/>/);
  assert.match(app, /settingsReturnPath/);
  assert.match(app, /return path|返回上一页/);
  assert.match(app, /topbar-leading/);
  assert.match(taskDrawer, /sessionStartedAt/);
  assert.doesNotMatch(router, /UpdatesPage|name: "updates"/);
  assert.match(taskDrawer, /refreshActiveTasks/);
  assert.match(taskDrawer, /进行中/);
  assert.match(taskDrawer, /任务记录/);
  assert.match(overview, /operations\.run\(/);
  assert.match(world, /operations\.run\(/);
  assert.match(world, /kind: "worldApply"/);
  assert.doesNotMatch(world, /applyBusy\.value = true/);
  assert.doesNotMatch(mods, /scheduleApplyPoll|getInstanceModApplyTask/);
  assert.match(mods, /taskStore\.tasks\.value/);
  assert.match(mods, /addSelectedHostLibrary/);
  assert.match(mods, /instanceModName/);
  assert.match(mods, /instanceModVersion/);
  assert.match(mods, /toggleHostLibraryItem/);
  assert.match(mods, /selectedHostLibraryItems/);
  assert.doesNotMatch(hostMods, /scheduleTaskPoll|getHostModTask/);
  assert.match(hostMods, /taskStore\.tasks\.value/);
  assert.match(hostMods, /checkAllUpdates/);
  assert.match(hostMods, /startBatchUpdate/);
  assert.match(hostMods, /useHostModBatch/);
  assert.match(hostMods, /checkOneUpdate/);
  assert.match(hostMods, /operations\.begin/);
  assert.match(hostMods, /hostModUpdate/);
  assert.doesNotMatch(hostMods, /pendingUpdateSync/);
  assert.doesNotMatch(hostMods, /previewSync\(updated\)/);
  assert.match(hostMods, /previewSync\(item\)/);
  assert.match(hostMods, /function invalidateQuery/);
  assert.match(hostMods, /if \(generation === queryGeneration\) queryBusy\.value = false/);
  assert.doesNotMatch(creation, /getInstanceCreateStatus|stopPolling/);
  assert.match(creation, /taskStore\.tasks\.value/);
  assert.doesNotMatch(backups, /scheduleRestorePoll|scheduleTaskPoll|getInstanceBackupTask|getInstanceRestoreTask/);
  assert.match(backups, /watch\(activeTask/);
  assert.match(backups, /const pageLoading = computed/);
  assert.match(backups, /:loading="pageLoading"/);
  assert.match(backups, /#empty/);
  assert.match(backups, /暂无备份/);
  assert.doesNotMatch(backups, /useInstanceOverview|overview\.refresh/);
  assert.match(backups, /listInstances/);
  assert.doesNotMatch(backups, /确认后会先检查归属、校验和、版本产物及空间/);
  assert.match(backups, /将恢复 <span class="mono">\{\{ restoreTarget\.backupId \}\}<\/span>/);
  assert.doesNotMatch(hostEnvironment, /scheduleDockerTaskPolling|stopDockerTaskPolling|taskPollTimer/);
  assert.match(hostEnvironment, /useDockerTasks/);
  assert.match(hostEnvironment, /useQuery/);
  assert.match(dockerTasks, /forHost/);
  assert.match(taskRefresh, /useDockerTasks/);
  assert.doesNotMatch(releases, /getBuildStatus|stopPolling|startPolling/);
  assert.match(releases, /useBuildTasks/);
  assert.match(buildTasks, /function start/);
  assert.match(buildTasks, /loadBuildTasks|saveBuildTasks/);
  assert.match(taskStoreSource, /loadTasks|saveTasks/);
  assert.match(operationsSource, /loadOperations|saveOperations/);
  assert.match(operationsSource, /interrupted/);
  assert.match(releaseList, /useQuery/);
  assert.doesNotMatch(releaseList, /currentConnection|onBeforeUnmount/);
  assert.match(instanceList, /useQuery/);
  assert.doesNotMatch(instanceList, /currentConnection/);
  assert.match(instanceOverview, /useQuery/);
  assert.doesNotMatch(instanceOverview, /isCurrentQuery|QueryTicket/);
  assert.match(hostModsPage, /useQuery/);
  assert.doesNotMatch(hostModsPage, /loadSequence|function current/);
  assert.match(taskDrawer, /buildRows/);
  assert.match(world, /readWorldDraft|writeWorldDraft/);
});
